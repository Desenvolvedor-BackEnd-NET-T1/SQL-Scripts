SELECT A.ID AS [MATRICULA], A.NOME, A.CPF, T.TELEFONE, A.DATA_CADASTRO AS [MATRICULADO EM]
 FROM ALUNO AS A INNER JOIN TELEFONE AS T ON A.ID  = T.ID_ALUNO
WHERE A.ID = 1010

SELECT A.ID AS [MATRICULA], A.NOME, A.CPF, T.TELEFONE, A.DATA_CADASTRO AS [MATRICULADO EM]
