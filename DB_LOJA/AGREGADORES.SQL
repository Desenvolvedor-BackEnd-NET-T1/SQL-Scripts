SELECT C.ID, 
       C.NOME, 
       COUNT(*) AS [QUANTIDADE DE PEDIDOS REALIZADOS], 
       SUM(VALOR_TOTAL) AS  [VALOR TOTAL GASTO NA LOJA ], 
       AVG(VALOR_TOTAL) AS [VALOR MEDIO POR PEDIDO], 
       SUM(QUANTIDADE_ITENS) AS [TOTAL ITENS COMPRADOS]
FROM CLIENTES AS C 
INNER JOIN PEDIDOS AS P  ON P.ID_CLIENTE = C.ID
GROUP BY C.ID, C.NOME





