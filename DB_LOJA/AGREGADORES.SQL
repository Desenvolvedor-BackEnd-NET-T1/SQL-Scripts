-- HAVING VERIFICARA TODOS OS CLIENTES QUE GASTARAM MAIS DE 5200 NA LOJA E RETORNARA
SELECT 
       C.ID,
       C.NOME, 
       SUM(VALOR_TOTAL) AS  [VALOR_TOTAL_POR_CLIENTE]
FROM CLIENTES AS C 
INNER JOIN PEDIDOS AS P  ON P.ID_CLIENTE = C.ID
--WHERE P.VALOR_TOTAL > 5200
GROUP BY C.ID, C.NOME
HAVING SUM(VALOR_TOTAL) > 5200



-- HAVING PARA EXIBIR SOMENTE OS CLIENTES QUE GASTARAM UMA MEDIA SUPERIOR DE 1000 REAIS POR PEDIDO 
SELECT 
       C.ID,
       C.NOME
FROM CLIENTES AS C 
INNER JOIN PEDIDOS AS P  ON P.ID_CLIENTE = C.ID
GROUP BY C.ID, C.NOME
HAVING AVG(VALOR_TOTAL) > 1000
