SELECT TELEFONE FROM CLIENTES_TELEFONES
UNION
SELECT TELEFONE FROM FORNECEDORES_TELEFONES
UNION 
SELECT TELEFONE FROM FUNCIONARIOS_TELEFONES 


--- UNION EXIBINDO NOVAS COLUNAS 

SELECT TELEFONE, 'CLIENTE' AS TIPO FROM CLIENTES_TELEFONES  
UNION
SELECT TELEFONE, 'FORNECEDORES' AS TIPO FROM FORNECEDORES_TELEFONES
UNION 
SELECT TELEFONE, 'FUNCIONARIOS' AS TIPO FROM FUNCIONARIOS_TELEFONES 



--- UNION EXIBINDO TIPO, E EXIBINDO O NOME DA PESSOA 

SELECT CT.TELEFONE, 'CLIENTE' AS TIPO , C.NOME
FROM CLIENTES_TELEFONES AS CT
INNER JOIN CLIENTES  AS C  ON C.ID = C.ID
UNION
SELECT FT.TELEFONE, 'FORNECEDORES' , F.RAZAO_SOCIAL
 FROM FORNECEDORES_TELEFONES AS FT 
INNER JOIN FORNECEDORES AS F ON F.ID = FT.ID_FORNECEDOR
UNION 
SELECT TELEFONE, 'FUNCIONARIOS' , F.NOME
FROM FUNCIONARIOS_TELEFONES AS FT 
INNER JOIN FUNCIONARIOS AS F ON F.MATRICULA = FT.ID_FUNCIONARIOS






SELECT CT.TELEFONE, 'CLIENTE' AS TIPO , C.NOME , C.CPF, NULL AS CNPJ
FROM CLIENTES_TELEFONES AS CT
INNER JOIN CLIENTES  AS C  ON C.ID = C.ID
UNION
SELECT FT.TELEFONE, 'FORNECEDORES' , F.RAZAO_SOCIAL, NULL, F.CNPJ
 FROM FORNECEDORES_TELEFONES AS FT 
INNER JOIN FORNECEDORES AS F ON F.ID = FT.ID_FORNECEDOR
UNION 
SELECT TELEFONE, 'FUNCIONARIOS' , F.NOME, '', NULL  
FROM FUNCIONARIOS_TELEFONES AS FT 
INNER JOIN FUNCIONARIOS AS F ON F.MATRICULA = FT.ID_FUNCIONARIOS