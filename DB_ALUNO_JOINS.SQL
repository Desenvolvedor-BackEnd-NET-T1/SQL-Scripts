USE DB_AULA


--INNER JOIN  - EXIBIR AS LINHAS QUE EXITEM EM AMBAS AS TABELAS. 

SELECT ALUNO.ID, ALUNO.NOME, ALUNO.DATA_CADASTRO, ALUNO.CPF, TELEFONE.ID, TELEFONE.TELEFONE, TELEFONE.ID_ALUNO
 FROM ALUNO INNER JOIN TELEFONE ON ALUNO.ID  = TELEFONE.ID_ALUNO

--USAR ALIAS (APELIDO) PARA RENOMEAR A EXIBIÇÃO DE COLUNAS 
SELECT ALUNO.ID AS [MATRICULA], ALUNO.NOME, ALUNO.CPF,  TELEFONE.TELEFONE, ALUNO.DATA_CADASTRO AS [MATRICULADO EM]
 FROM ALUNO INNER JOIN TELEFONE ON ALUNO.ID  = TELEFONE.ID_ALUNO

--APLICAR FILTROS COM WHERE 
SELECT ALUNO.ID AS [MATRICULA], ALUNO.NOME, ALUNO.CPF,  TELEFONE.TELEFONE, ALUNO.DATA_CADASTRO AS [MATRICULADO EM]
 FROM ALUNO INNER JOIN TELEFONE ON ALUNO.ID  = TELEFONE.ID_ALUNO
 WHERE ALUNO.ID = 1010

--ORDENAÇÃO 
SELECT ALUNO.ID AS [MATRICULA], ALUNO.NOME, ALUNO.CPF,  TELEFONE.TELEFONE, ALUNO.DATA_CADASTRO AS [MATRICULADO EM]
 FROM ALUNO INNER JOIN TELEFONE ON ALUNO.ID  = TELEFONE.ID_ALUNO
 ORDER BY ALUNO.ID DESC

 -- UTILIZAR ALIAS (APELIDOS) PARA AS TABELAS 
